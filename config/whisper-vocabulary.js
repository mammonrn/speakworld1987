/** ใช้เมื่อแชทยังไม่เคยตั้งภาษาปลายทาง — กลางๆ ไม่เอนไปทางปลายทางไหน */
const GENERIC = [
  'กรุงเทพ',
  'สุวรรณภูมิ',
  'ดอนเมือง',
  'เชียงใหม่',
  'ภูเก็ต',
  'พัทยา',
  'หัวหิน',
  'อยุธยา',
];

/**
 * รายการคำศัพท์ของภาษาปลายทางที่ระบุ
 * @param {string} [languageCode] เช่น 'my', 'zh-CN' (ไม่ระบุ = ชุดกลาง)
 * @returns {string[]}
 */
function vocabularyFor(languageCode) {
  if (!languageCode) return GENERIC;
  const key = String(languageCode).toLowerCase().split('-')[0];
  return VOCABULARY[key] || GENERIC;
}

/**
 * ต่อคำศัพท์เป็น prompt string สำหรับส่งให้ Whisper
 * @param {string} [languageCode]
 * @returns {string}
 */
function promptFor(languageCode) {
  return vocabularyFor(languageCode).join(', ');
}

module.exports = { VOCABULARY, GENERIC, vocabularyFor, promptFor };
